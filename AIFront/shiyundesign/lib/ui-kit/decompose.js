'use strict'

const { mkdirSync, writeFileSync } = require('node:fs')
const { join, dirname } = require('node:path')

const SCHEMA_VERSION = 1

function sanitizeSlug (slug) {
  return String(slug || '')
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '') || 'untitled'
}

function renderTokensCss (tokens) {
  const grouped = {}
  for (const t of tokens) {
    const bucket = grouped[t.category] || []
    bucket.push(t)
    grouped[t.category] = bucket
  }
  const lines = [':root {']
  for (const [category, items] of Object.entries(grouped)) {
    lines.push(`  /* ${category} */`)
    for (const t of items) {
      const name = t.name.startsWith('--') ? t.name : `--${t.name}`
      lines.push(`  ${name}: ${t.value};`)
    }
  }
  lines.push('}')
  return lines.join('\n') + '\n'
}

function renderManifest (slug, components, tokens) {
  const tokenCounts = {}
  for (const t of tokens) {
    tokenCounts[t.category] = (tokenCounts[t.category] || 0) + 1
  }
  return JSON.stringify({
    schemaVersion: SCHEMA_VERSION,
    generator: 'shiyundesign decompose-ui-kit',
    generatedAt: new Date().toISOString(),
    slug,
    components: components.map((c) => c.name),
    tokens: tokenCounts
  }, null, 2) + '\n'
}

function renderReadme (slug, components, notes) {
  const lines = [
    `# ${slug}`,
    '',
    'Generated by ShiyunDesign `decompose-ui-kit`. Hand off this folder to a coding agent.',
    '',
    '## Files',
    '- `index.html` — page-level HTML',
    '- `components/*` — reusable components',
    '- `tokens.css` — design tokens',
    '- `manifest.json` — machine-readable summary',
    '',
    '## Components'
  ]
  if (!components.length) lines.push('_(none extracted)_')
  else {
    for (const c of components) {
      const summary = c.propsSummary ? ` — ${c.propsSummary}` : ''
      lines.push(`- **${c.name}** (\`components/${c.filename}\`)${summary}`)
    }
  }
  if (notes?.trim()) lines.push('', '## Notes', notes.trim())
  return lines.join('\n') + '\n'
}

function writeFile (filePath, content) {
  mkdirSync(dirname(filePath), { recursive: true })
  writeFileSync(filePath, content, 'utf8')
}

/**
 * @param {string} cwd
 * @param {{ slug: string, indexHtml: string, components?: Array<{ name: string, filename: string, source: string, propsSummary?: string }>, tokens?: Array<{ name: string, value: string, category: string }>, readmeNotes?: string }} plan
 */
function decomposeUiKit (cwd, plan) {
  const slug = sanitizeSlug(plan.slug)
  const base = join(cwd, 'ui_kits', slug)
  const components = Array.isArray(plan.components) ? plan.components : []
  const tokens = Array.isArray(plan.tokens) ? plan.tokens : []
  const written = []

  writeFile(join(base, 'index.html'), plan.indexHtml)
  written.push(`ui_kits/${slug}/index.html`)

  for (const comp of components) {
    const rel = join('ui_kits', slug, 'components', comp.filename)
    writeFile(join(cwd, rel), comp.source)
    written.push(rel.replace(/\\/g, '/'))
  }

  writeFile(join(base, 'tokens.css'), renderTokensCss(tokens))
  written.push(`ui_kits/${slug}/tokens.css`)

  writeFile(join(base, 'manifest.json'), renderManifest(slug, components, tokens))
  written.push(`ui_kits/${slug}/manifest.json`)

  writeFile(join(base, 'README.md'), renderReadme(slug, components, plan.readmeNotes))
  written.push(`ui_kits/${slug}/README.md`)

  return { slug, componentCount: components.length, tokenCount: tokens.length, outputPaths: written }
}

module.exports = { decomposeUiKit, sanitizeSlug }
